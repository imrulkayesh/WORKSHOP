using System;
using System.Collections.Generic;
using System.Data;
using System.Linq;
using System.Web;

public class dalDispatchReport
{
    DatabaseManagerORCL dm = new DatabaseManagerORCL();
    public dalDispatchReport()
    {
    }
    public DataTable GetByCriteria(string Criteria)
    {
        return dm.ExecuteQuery("SELECT * FROM VW_DISPATCHREPORT WHERE ID>0 " + Criteria);
    }

    public DataTable GetByGeteEntryDetails(string Criteria)
    {
        return dm.ExecuteQuery(@"SELECT GE.*, EM.EMPLOYEENAME,EM.OFFICEMOBILE, EM.STAFFID,BC.CENTERNAME, BC.CENTERCODE,D.DEPARTMENTNAME,D.DEPARTMENTCODE
        FROM DP_GATEENTRY GE 
        INNER JOIN EM_EMPLOYEE EM ON EM.STAFFID = GE.CREATEDBY
        INNER JOIN BS_BUSINESSCENTER BC ON BC.ID = GE.BUSINESSCENTERID
        INNER JOIN BS_DEPARTMENT D ON D.ID = GE.DEPARTMENTID WHERE GE.ID>0 " + Criteria);
    }

    public DataTable GetByGeteEntryReturnItem(string Criteria)
    {
        return dm.ExecuteQuery(@"SELECT GE.*, EI.ISRETURNABLE, EI.ISPERSONAL, EM.EMPLOYEENAME,EM.OFFICEMOBILE, EM.STAFFID,BC.CENTERNAME, BC.CENTERCODE,
        D.DEPARTMENTNAME,D.DEPARTMENTCODE FROM DP_GATEENTRY GE 
        INNER JOIN DP_GATEENTRYITEMS EI ON EI.GATEENTRYID= GE.ID
        INNER JOIN EM_EMPLOYEE EM ON EM.STAFFID = GE.CREATEDBY
        INNER JOIN BS_BUSINESSCENTER BC ON BC.ID = GE.BUSINESSCENTERID
        INNER JOIN BS_DEPARTMENT D ON D.ID = GE.DEPARTMENTID WHERE GE.ID>0 AND GE.ISRETURNED=1  " + Criteria);
    }

    public DataTable GetDispatchDetails(string Criteria)
    {
        return dm.ExecuteQuery(@"SELECT D.ID, D.CREATEDATE,RC.CENTERNAME RECEIVERLOC, D.TRANSACTIONID, I.ISSUETYPENAME, FB.CENTERNAME,DP.DEPARTMENTNAME, D.FROMUSER, D.SENDNAME,
        D.SENDMOBILE, D.TOUSER, D.RECEIVERNAME, D.RECEIVERMOBILE, DI.ITEMNAME, DI.QUANTITY, DI.UNIT, DI.NOTES,
        (SELECT STEP FROM DP_TRANSITS WHERE DISPATCHID = D.ID AND ISACTIVE = 1 AND ROWNUM = 1) STEP,
        (SELECT SUM (D.UPDATEDBY) FROM DP_DISPATCH D WHERE D.UPDATEDBY = CE.STAFFID) APPROVERSTAFFID
        FROM DP_DISPATCH D
        INNER JOIN DP_DISPATCHITEMS DI ON DI.DISPATCHID = D.ID 
        INNER JOIN EM_EMPLOYEE CE ON CE.STAFFID = D.CREATEDBY
        LEFT OUTER JOIN DP_APPROVER DA ON DA.APPROVERID = D.UPDATEDBY 
        INNER JOIN BS_BUSINESSCENTER FB ON FB.ID = D.SENDBUSINESSCENTERID 
INNER JOIN EM_EMPLOYEE RV ON D.TOUSER = RV.USERID
INNER JOIN BS_BUSINESSCENTER RC ON RV.BUSINESSCENTERID = RC.ID
        INNER JOIN BS_DEPARTMENT DP ON DP.ID = D.SENDDEPARTMENTID
        INNER JOIN DP_ISSUETYPE I ON I.ID = D.ISSUETYPEID
        INNER JOIN BS_DEPARTMENT FD ON FD.ID = D.SENDDEPARTMENTID
        WHERE D.ID >0 " + Criteria + " "+"GROUP BY D.ID,D.CREATEDATE, D.TRANSACTIONID, I.ISSUETYPENAME,FB.CENTERNAME," +
                               " D.FROMUSER, D.SENDNAME, D.SENDMOBILE, D.TOUSER, D.RECEIVERNAME, D.RECEIVERMOBILE, DI.ITEMNAME," +
                               " DI.QUANTITY,RC.CENTERNAME, DI.UNIT, DI.NOTES, CE.UPDATEDBY, CE.STAFFID,DP.DEPARTMENTNAME, CE.EMPLOYEENAME");
    }

    public DataTable GetDispatchDetailsextra()
    {
                return dm.ExecuteQuery(@"SELECT D.ID, D.CREATEDATE, D.TRANSACTIONID, I.ISSUETYPENAME, FB.CENTERNAME, D.FROMUSER, D.SENDNAME,
