using System;
using System.Collections.Generic;
using System.Data;
using System.Linq;
using System.Web;


public class dalLocationWiseReport
{
    DatabaseManagerORCL dm = new DatabaseManagerORCL();
    public dalLocationWiseReport()
    {

    }
    public DataTable GetByCriteria(string Criteria)
    {
        return dm.ExecuteQuery(@"SELECT E.EMPLOYEENAME,E.STAFFID, E.OFFICEMOBILE,E.OFFICEMAIL,A.*,B.CENTERNAME,C.COMPANYNAME, DE.DEPARTMENTNAME,
        DE.DEPARTMENTCODE, DS.DESIGNATIONNAME FROM DP_APPROVER A
         INNER JOIN BS_BUSINESSCENTER B ON B.ID = A.BUSINESSCENTERID
         INNER JOIN BS_COMPANY C ON C.ID = A.COMPANYID
         INNER JOIN BS_DEPARTMENT DE ON DE.ID = A.DEPARTMENTID
         INNER JOIN EM_EMPLOYEE E ON E.USERID = A.APPROVERID
         INNER JOIN BS_DESIGNATION DS ON DS.ID = E.DESIGNATIONID WHERE LENGTH(E.STAFFID)>0 " + Criteria);
    }

    public DataTable GetAllUserList(string Criteria)
    {
        return dm.ExecuteQuery(@"SELECT E.STAFFID,E.EMPLOYEENAME,E.OFFICEMAIL,E.OFFICEMOBILE,U.ROLEID,R.ROLENAME, B.CENTERCODE, B.CENTERNAME,
                    C.COMPANYNAME,DE.DEPARTMENTCODE,DE.DEPARTMENTNAME,DS.DESIGNATIONNAME
         FROM EM_EMPLOYEE E
         INNER JOIN UC_USERS U ON U.ID = E.STAFFID
         INNER JOIN UC_ROLESETUP R ON R.ID = U.ROLEID
         INNER JOIN BS_BUSINESSCENTER B ON B.ID = E.BUSINESSCENTERID
         INNER JOIN BS_COMPANY C ON C.ID = E.COMPANYID
         INNER JOIN BS_DEPARTMENT DE ON DE.ID = E.DEPARTMENTID
         INNER JOIN BS_DESIGNATION DS ON DS.ID = E.DESIGNATIONID WHERE LENGTH(E.STAFFID)>0 " + Criteria);
    }

    public DataTable GetUserInfomationt(string staffid)
    {
        return dm.ExecuteQuery(@"SELECT E.STAFFID,E.EMPLOYEENAME,E.OFFICEMAIL,E.OFFICEMOBILE,U.ROLEID,R.ROLENAME, B.CENTERCODE, B.CENTERNAME,
                    C.COMPANYNAME,DE.DEPARTMENTCODE,DE.DEPARTMENTNAME,DS.DESIGNATIONNAME
         FROM EM_EMPLOYEE E
         INNER JOIN UC_USERS U ON U.ID = E.STAFFID
         INNER JOIN UC_ROLESETUP R ON R.ID = U.ROLEID
         INNER JOIN BS_BUSINESSCENTER B ON B.ID = E.BUSINESSCENTERID
         INNER JOIN BS_COMPANY C ON C.ID = E.COMPANYID
         INNER JOIN BS_DEPARTMENT DE ON DE.ID = E.DEPARTMENTID
         INNER JOIN BS_DESIGNATION DS ON DS.ID = E.DESIGNATIONID 
         WHERE LENGTH(E.STAFFID)>0 AND E.STAFFID='"+staffid+"'");
    }
}